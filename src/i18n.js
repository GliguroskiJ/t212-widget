let LANG = 'en';
export const setLang = l => { LANG = l === 'cs' ? 'cs' : 'en'; };
export const lang = () => LANG;
export const locale = () => (LANG === 'cs' ? 'cs-CZ' : 'en-GB');

export function t(s, vars) {
  let out = LANG === 'cs' && CS[s] != null ? CS[s] : s;
  if (vars) for (const k of Object.keys(vars)) out = out.split('{' + k + '}').join(vars[k]);
  return out;
}

